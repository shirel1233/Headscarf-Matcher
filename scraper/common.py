"""פונקציות עזר משותפות לכל הסורקים: זיהוי צבע, דוגמה, וסינון מטפחות."""

# מילים שמזהות מטפחת/צעיף (לסינון כשבאתר נמכרים גם דברים אחרים)
SCARF_KEYWORDS = [
    "מטפחת", "מטפחות", "צעיף", "צעיפים", "בנדנה", "טורבן", "שאל", "כיסוי ראש",
    "scarf", "headscarf", "hijab", "turban", "bandana",
]

# רשימת צבעים בעברית (סדר לא משנה, נבחר הצבע שמופיע ראשון בטקסט)
COLORS = [
    "שחור", "לבן", "אפור", "בז'", "בז׳", "קרם", "שמנת", "חום", "קפה", "חרדל",
    "צהוב", "כתום", "אדום", "בורדו", "יין", "ורוד", "פוקסיה", "סגול", "לילך",
    "כחול", "נייבי", "תכלת", "טורקיז", "ירוק", "זית", "מנטה", "זהב", "כסף",
    "קאמל", "אפרסק", "מרווה", "חרדל", "עור",
]

# דוגמאות: שם הדוגמה -> מילים שמעידות עליה
PATTERNS = {
    "פרחוני": ["פרחוני", "פרחים", "פרח"],
    "פסים": ["פסים", "פסי "],
    "משבצות": ["משבצות", "משובץ", "קארו"],
    "נקודות": ["נקודות", "מנוקד", "פולקה"],
    "גיאומטרי": ["גיאומטרי"],
    "טקסטורה": ["טקסטורה", "קרינקל", "פליסה", "קפלים"],
    "הדפס": ["הדפס", "מודפס", "דוגמה", "דוגמת"],
    "חלק": ["חלק", "אחיד"],
}

UNKNOWN_COLOR = "לא ידוע"


def find_first_color(text: str):
    """מחזיר את הצבע שמופיע ראשון בטקסט, או None."""
    best = None
    for color in COLORS:
        pos = text.find(color)
        if pos != -1 and (best is None or pos < best[0]):
            best = (pos, color)
    return best[1] if best else None


def find_pattern(text: str):
    """מחזיר שם דוגמה לפי מילות מפתח, או None."""
    for pattern_name, words in PATTERNS.items():
        if any(w in text for w in words):
            return pattern_name
    return None


def looks_like_scarf(text: str) -> bool:
    low = text.lower()
    return any(k in low for k in SCARF_KEYWORDS)
